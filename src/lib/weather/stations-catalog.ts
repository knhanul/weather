function officeRegion(office: string): string {
  if (office.includes("제주")) return "제주";
  if (
    office.includes("수도권") ||
    office.includes("인천")
  ) {
    return "수도권";
  }
  if (office.includes("강원") || office.includes("춘천")) return "강원";
  if (
    office.includes("청주") ||
    office.includes("대전") ||
    office.includes("홍성")
  ) {
    return "충청";
  }
  if (
    office.includes("전주") ||
    office.includes("광주") ||
    office.includes("목포")
  ) {
    return "전라";
  }
  return "경상";
}

